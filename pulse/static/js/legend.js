export function openLegend() {
  const body = document.createElement('div');
  body.innerHTML = html`
    <p class="small muted" style="margin-bottom:1rem">Every symbol in Pulse, explained. Reading labels appear on every card so you always know whether a story opens here or at the publisher.</p>
    <div class="legend-grid">
      ${GROUPS.map((group) => html`
        <section class="legend-group">
          <h3>${group.title}</h3>
          ${group.items.map(([icon, label, description]) => html`
            <div class="legend-item">
              <span class="legend-item__icon" aria-hidden="true">${icon}</span>
              <span><b>${label}</b><span class="legend-item__desc">${description}</span></span>
            </div>`)}
        </section>`)}
    </div>
    <p class="tiny faint" style="margin-top:1rem">Keyboard: <kbd class="kbd">⌘K</kbd> search, <kbd class="kbd">/</kbd> search, <kbd class="kbd">?</kbd> this key, <kbd class="kbd">esc</kbd> close.</p>`;
  const box = modal({
    title: 'Key to symbols',
    wide: true,
    body,
    actions: [{ label: 'Got it', class: 'btn--primary' }],
  });
  void box;
  void raw;
}
